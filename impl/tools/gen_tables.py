#!/usr/bin/env python3
"""One-shot generator (already applied): the default funmap order and the
default keymaps, from black-box observations of the reference driver
(impl/tools/observed/: `get funmap` after rl_initialize, `keymap_dump MAP`
before rl_initialize, `rl-driver --bindable`).  Writes
impl/src/funmap_table.rs and impl/src/keymap/defaults.rs."""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), "src")
OBS = os.path.join(HERE, "observed")

# where each public function lives
where = {}
for dp, _, fs in os.walk(SRC):
    for f in fs:
        if not f.endswith(".rs"): continue
        rel = os.path.relpath(os.path.join(dp, f), SRC)[:-3]
        mod = "crate::" + rel.replace("/mod", "").replace("/", "::")
        for m in re.finditer(r'extern "C" fn (\w+)\(', open(os.path.join(dp, f)).read()):
            where[m.group(1)] = mod

def rec(path):
    out = []
    for line in open(path):
        m = re.match(r"\s*results\[(\d+)\] (.*)", line)
        if m: out.append(json.loads(m.group(2)))
    return out

funmap = [n for n in rec(os.path.join(OBS, "funmap.txt"))[0]["ret"] if not n.startswith("driver-")]
first = {}
for line in open(os.path.join(OBS, "bindable.txt")):
    c, n = line.split()
    if n != "?unknown": first[n] = c
ALIAS = {"vi-bWord": "rl_vi_bWord", "vi-bword": "rl_vi_bword", "vi-end-bigword": "rl_vi_eWord",
         "vi-forward-bigword": "rl_vi_fWord", "vi-fword": "rl_vi_fword", "vi-backward-word": "rl_vi_bword"}
name2c = {}
for n in funmap:
    c = first.get(n) or ALIAS.get(n)
    assert c, n
    name2c[n] = c

with open(os.path.join(SRC, "funmap_table.rs"), "w") as f:
    f.write("//! GENERATED by impl/tools/gen_tables.py: default funmap entries in the\n"
            "//! reference's order (first entry wins for function -> name lookups).\n"
            "use crate::types::rl_command_func_t;\n\n"
            "pub static DEFAULT_FUNMAP: &[(&core::ffi::CStr, rl_command_func_t)] = &[\n")
    for n in funmap:
        c = name2c[n]
        f.write(f'    (c"{n}", {where[c]}::{c}),\n')
    f.write("];\n")

def decode(ks):
    """driver keyname notation -> list of key codes (256 = <any>)"""
    out = []; i = 0
    while i < len(ks):
        meta = 0
        if ks.startswith("\\M-", i): meta = 128; i += 3
        if ks.startswith("<any>", i): out.append(256); i += 5; continue
        if ks.startswith("\\e", i): k = 27; i += 2
        elif ks.startswith("\\C-?", i): k = 127; i += 4
        elif ks.startswith("\\C-", i): k = ord(ks[i+3].upper()) - 64; i += 4
        elif ks[i] == "\\": k = ord(ks[i+1]); i += 2
        else: k = ord(ks[i]); i += 1
        out.append(k + meta)
    return out

MAPS = [("emacs-standard", "emacs_standard_keymap"), ("emacs-meta", "emacs_meta_keymap"),
        ("emacs-ctlx", "emacs_ctlx_keymap"), ("vi-move", "vi_movement_keymap"),
        ("vi-insert", "vi_insertion_keymap")]
VAR = dict(MAPS)
dumps = {r["op"].split()[1]: r["ret"] for r in rec(os.path.join(OBS, "keymaps-preinit.txt"))}
with open(os.path.join(SRC, "keymap", "defaults.rs"), "w") as f:
    f.write("//! GENERATED by impl/tools/gen_tables.py: the five default keymaps as the\n"
            "//! reference has them before rl_initialize (arrow keys etc. are bound at\n"
            "//! initialisation, see keymap::bind_default_keyseqs).\n"
            "#![allow(clippy::all)]\n"
            "use crate::prelude::*;\n\n"
            "const E: KEYMAP_ENTRY = KEYMAP_ENTRY::EMPTY;\n"
            "const fn f(c: rl_command_func_t) -> KEYMAP_ENTRY { KEYMAP_ENTRY::func(c) }\n\n")
    for dn, var in MAPS:
        ent = ["E"] * 257
        for ks, typ, val in dumps[dn]:
            keys = decode(ks)
            assert len(keys) == 1, ks
            k = keys[0]
            if typ == "func":
                c = name2c[val]
                ent[k] = f"f({where[c]}::{c})"
            elif typ == "keymap":
                ent[k] = f"KEYMAP_ENTRY::keymap({VAR[val]}.as_ptr() as Keymap)"
            else:
                raise SystemExit("macro in default map")
        f.write(f"#[no_mangle]\npub static {var}: CVar<KEYMAP_ENTRY_ARRAY> = CVar::new([\n")
        for k, e in enumerate(ent):
            f.write(f"    {e}, // {k}\n")
        f.write("]);\n\n")
print("ok", len(funmap))
